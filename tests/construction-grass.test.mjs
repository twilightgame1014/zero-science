import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {loadTerrain} from './helpers/terrain.mjs';
const require=createRequire(import.meta.url);
require('../src/game/construction-data.js');require('../src/game/space-data.js');
const D=require('../src/game/data.js'),E=require('../src/game/engine.js'),N=require('../src/game/nature.js'),C=require('../src/game/construction.js');
const T=await loadTerrain(),W=N.create(D,E,{...T,cfg:T.DEFAULT_CONFIG});
const fresh=()=>{const s=E.newState();s.cons.rule='build';return s;};
const now=1000000,s=fresh();
const grass=W.objects.find(o=>o.kind==='grass'&&C.roadPlan(s,W,'dirt',o,o,now).ok);
assert(grass,'a natural grass cell can be paved');
const q=C.cellOf(grass.x,grass.z),p=C.cellCenter(q.i,q.j);
const objects=W.around(p.x,p.z,D.construction.CELL).filter(o=>o.kind==='grass'&&C.cellOf(o.x,o.z).i===q.i&&C.cellOf(o.x,o.z).j===q.j);
const reference=E.deserialize(E.serialize(s)),random=Math.random;Math.random=()=>.99;
try{
 for(const o of objects)assert(W.harvest(reference,o.id,{pos:o,now,token:reference.seq}).ok);
 const plan=C.planRoad(s,W,'dirt',p,p,now,s.seq);assert(plan.ok);const id=plan.ids[0];
 assert.equal(E.cnt(s,'grass'),0,'planning grants no resources');
 assert(W.present(s,grass,now),'planned grass still exists');
 for(const [item,n]of Object.entries(C.remainingNeed(s.cons.inst[id])))E.addItem(s,item,n,'test');
 C.deliverAll(s,W,id,p,s.seq);
 assert(C.startWork(s,W,id,p,now,s.seq).ok);
 assert(!C.finishWork(s,W,id,p,now,s.seq).ok,'work must finish');
 assert(!C.finishWork(s,W,id,{x:p.x+100,z:p.z},now+10000,s.seq).ok,'must return to site');
 const token=s.seq;const finish=C.finishWork(s,W,id,p,now+10000,token);assert(finish.ok);
 assert.equal(E.cnt(s,'grass'),E.cnt(reference,'grass'),'same normal harvest rewards');
 assert.deepEqual(finish.cleared,{grass:E.cnt(reference,'grass')});
 assert(!C.finishWork(s,W,id,p,now+10000,token).ok,'duplicate token denied');
 const loaded=E.deserialize(E.serialize(s));assert.equal(E.cnt(loaded,'grass'),E.cnt(s,'grass'));
 assert(!W.present(loaded,grass,now+1000000),'completed road suppresses regrowth');
 assert.equal(W.visual(loaded,grass,now+1000000).state,'gone');
 assert(!W.harvest(loaded,grass.id,{pos:grass,now:now+1000000,token:loaded.seq}).ok,'no hidden-road harvesting');
 assert(!C.planRoad(loaded,W,'dirt',p,p,now+1000000,loaded.seq).ok,'same road cannot be farmed');
 assert(C.removeRoadCells(loaded,[C.cellKey(q.i,q.j)],loaded.seq).ok);
 assert(W.present(loaded,grass,now+1000000),'removal restores natural timed regrowth');
 const cancelled=fresh(),r=C.planRoad(cancelled,W,'dirt',p,p,now,cancelled.seq);assert(r.ok);assert(C.remove(cancelled,r.ids[0],cancelled.seq).ok);
 assert.equal(E.cnt(cancelled,'grass'),0,'cancelled plan grants nothing');assert(W.present(cancelled,grass,now));
}finally{Math.random=random;}
console.log('PASS road auto-harvest: normal yield, planning/cancel, time/distance, duplicate, reload, road regrowth suppression and removal');
