#!/usr/bin/env python3
"""Process the owner's GPT material sheets into game-ready PBR tiles.

Sources (assets/buildings-3d/source-gpt/, each 1206x1206, 2x2):
  sheet-1: TL planks      TR thatch     BL earth_wall  BR bark
  sheet-2: TL stone_wall  TR fired_clay BL brick       BR roof_tile
  sheet-3: TL cast_iron   TR copper     BL metal_roof  BR plaster

Per material (all outputs 512x512 in assets/buildings-3d/textures/):
  <name>.png    albedo  - quadrant crop inset from the seams, baked
                shading flattened mildly, saturation/contrast tamed;
                made tileable (structured materials are cropped to a
                whole number of pattern periods; organic materials get
                a half-roll crossfade at the borders)
  <name>_n.png  normal  - derived from STRUCTURE only (mortar joints,
                plank gaps, tile overlaps, bark ridges, panel ribs).
                Colour variation (wood grain colour, copper patina,
                clay cracks) is deliberately NOT turned into bumps.
  <name>_r.png  roughness - absolute values: base per material plus
                structure-driven variation (mortar rougher than brick
                faces, copper patina rougher than polished copper).

Also writes previews/tiling-<name>.png (2x2) and a seam report.
Auxiliary sprites (log end grain, soot decal, flame card, contact
shadow) are generated by make_aux_textures() at the bottom.
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "source-gpt"
OUT = HERE.parent / "textures"
PREV = HERE.parent / "previews"
SIZE = 512
INSET = 12  # px kept away from quadrant borders (neighbour bleed)

# name -> (sheet, quadrant TL/TR/BL/BR, mode, world tile metres)
MATERIALS = {
    "planks":    ("sheet-1", "TL", "period-x", 1.1),
    "thatch":    ("sheet-1", "TR", "period-y+xf", 1.2),
    "earth":     ("sheet-1", "BL", "organic", 1.6),
    "bark":      ("sheet-1", "BR", "organic", 0.9),
    "stone":     ("sheet-2", "TL", "organic", 1.6),
    "clay":      ("sheet-2", "TR", "organic", 1.4),
    "brick":     ("sheet-2", "BL", "period-xy", 1.0),
    "tile":      ("sheet-2", "BR", "period-xy", 1.0),
    "iron":      ("sheet-3", "TL", "organic", 1.4),
    "copper":    ("sheet-3", "TR", "organic", 1.2),
    "metalroof": ("sheet-3", "BL", "period-x", 1.2),
    "plaster":   ("sheet-3", "BR", "organic", 1.8),
}
QUAD = {"TL": (0, 0), "TR": (1, 0), "BL": (0, 1), "BR": (1, 1)}


# ------------------------------------------------------------ helpers

def lum(a):
    return a[..., 0] * 0.299 + a[..., 1] * 0.587 + a[..., 2] * 0.114


def blur(a, radius):
    im = Image.fromarray(np.clip(a * 255, 0, 255).astype(np.uint8))
    im = im.filter(ImageFilter.GaussianBlur(radius))
    return np.asarray(im).astype(np.float64) / 255.0


def blur1(a, radius):
    """Single-channel blur for float arrays in [0,1]."""
    im = Image.fromarray(np.clip(a * 255, 0, 255).astype(np.uint8))
    im = im.filter(ImageFilter.GaussianBlur(radius))
    return np.asarray(im).astype(np.float64) / 255.0


GRADE_TWEAK = {  # name -> (flatten strength, saturation, brightness)
    "planks": (0.50, 0.92, 1.00),   # calm the scorched-looking grain
    "thatch": (0.50, 0.92, 1.00),   # lift baked bundle shadows
    "bark":   (0.35, 0.92, 1.16),   # bark crushes to black in game light
    "iron":   (0.35, 0.90, 1.38),   # cast iron must not read pure black
    "stone":  (0.35, 0.75, 1.00),   # warm mortar made walls look fleshy
}


def grade(a, name=""):
    """Flatten baked shading mildly, tame saturation and contrast."""
    flat, sat, bright = GRADE_TWEAK.get(name, (0.35, 0.92, 1.0))
    a = a.astype(np.float64) / 255.0
    low = blur1(lum(a), 42)
    ratio = (low.mean() / np.maximum(low, 1e-4)) ** flat
    a = np.clip(a * ratio[..., None], 0, 1)
    g = lum(a)
    a = g[..., None] + (a - g[..., None]) * sat           # saturation
    a = np.clip((a - 0.5) * 0.95 + 0.5, 0, 1)             # contrast
    return np.clip(a * bright, 0, 1)


def find_period(proj, lo, hi):
    """Dominant period of a 1-D projection via autocorrelation."""
    p = proj - proj.mean()
    ac = np.correlate(p, p, "full")[len(p) - 1:]
    if ac[0] <= 0:
        return None
    seg = ac[lo:hi]
    if len(seg) == 0:
        return None
    k = int(np.argmax(seg)) + lo
    return k if ac[k] > 0.25 * ac[0] else None


def crop_periods(img, mode):
    """Crop to a whole number of pattern periods (structured mats)."""
    a = np.asarray(img).astype(np.float64)
    L = lum(a / 255.0)
    h, w = L.shape
    x0, x1, y0, y1 = 0, w, 0, h
    if "x" in mode:
        per = find_period(L.mean(axis=0), 50, 210)
        if per:
            n = max(1, int(w / per))
            nw = n * per
            x0 = (w - nw) // 2
            x1 = x0 + nw
    if "y" in mode:
        per = find_period(L.mean(axis=1), 30, 210)
        if per:
            n = max(1, int(h / per))
            nh = n * per
            y0 = (h - nh) // 2
            y1 = y0 + nh
    return img.crop((x0, y0, x1, y1))


def crossfade(a):
    """Make an organic texture tileable: crossfade against the
    half-rolled copy near the borders (weight 1 at the edge)."""
    s = a.shape[0]

    def weights(n):
        d = np.minimum(np.arange(n), n - 1 - np.arange(n)) + 0.5
        return np.clip(1.0 - d / (n * 0.25), 0, 1)

    for axis in (1, 0):
        r = np.roll(a, a.shape[axis] // 2, axis=axis)
        w = weights(a.shape[axis])
        shape = [1, 1, 1]
        shape[axis] = -1
        w = w.reshape(shape)
        a = (1 - w) * a + w * r
    return a


def seam_ratio(a):
    """|jump across the wrap| vs |typical interior step| (1.0 = clean)."""
    L = lum(a)
    jx = np.abs(L[:, 0] - L[:, -1]).mean()
    ix = np.abs(np.diff(L, axis=1)).mean()
    jy = np.abs(L[0, :] - L[-1, :]).mean()
    iy = np.abs(np.diff(L, axis=0)).mean()
    return float((jx + jy) / max(ix + iy, 1e-9))


# ------------------------------------------------------------ normals

def height_to_normal(h, strength):
    """Sobel normals from a height field, wrap-around gradients."""
    gx = (np.roll(h, -1, axis=1) - np.roll(h, 1, axis=1))
    gy = (np.roll(h, -1, axis=0) - np.roll(h, 1, axis=0))
    # smooth the gradient a touch to keep the pixel look calm
    gx = blur1((gx + 1) / 2, 0.7) * 2 - 1
    gy = blur1((gy + 1) / 2, 0.7) * 2 - 1
    nx, ny, nz = -gx * strength, gy * strength, np.ones_like(h)
    n = np.stack([nx, ny, nz], axis=-1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    return ((n * 0.5 + 0.5) * 255).astype(np.uint8)


def fine_noise(shape, radius, seed):
    rng = np.random.default_rng(seed)
    n = rng.random(shape)
    return blur1(n, radius)


def mortar_mask_brick(L, a):
    """Brick mortar: brighter and less saturated than the bricks."""
    sat = a.max(axis=-1) - a.min(axis=-1)
    m = ((L > 0.52) & (sat < 0.34)).astype(np.float64)
    return blur1(m, 1.2)


def mortar_mask_stone(L, a):
    """Stone-wall mortar: warm, sandy, darker than the stones."""
    warm = a[..., 0] - a[..., 2]
    m = ((warm > 0.10) & (L < 0.52)).astype(np.float64)
    return blur1(m, 1.4)


def build_height(name, a):
    """Height from structure only (see module docstring)."""
    L = lum(a)
    if name == "planks":
        # vertical gaps between boards: dark thin vertical lines
        col = blur1(L, 0.8)
        gap = np.clip((0.42 - col) * 3.0, 0, 1)
        gap = blur1(gap, 0.7)
        return 0.55 - gap * 0.55 + fine_noise(L.shape, 1.2, 11) * 0.05
    if name == "thatch":
        row = blur1(L, 1.0)
        groove = np.clip((np.median(row) - row) * 2.2, 0, 1)
        strands = fine_noise(L.shape, 0.5, 12)
        strands = blur1(strands, 0.4)
        return 0.6 - blur1(groove, 1.0) * 0.5 + strands * 0.10
    if name == "earth":
        return 0.5 + fine_noise(L.shape, 26, 13) * 0.25 \
            + fine_noise(L.shape, 1.4, 14) * 0.10
    if name == "bark":
        base = blur1(L, 1.0)
        stretched = np.asarray(Image.fromarray(
            (base * 255).astype(np.uint8)).resize(
            (128, 512), Image.BILINEAR).resize(
            (512, 512), Image.BILINEAR)).astype(np.float64) / 255.0
        return stretched * 0.85 + fine_noise(L.shape, 0.8, 15) * 0.08
    if name == "stone":
        m = mortar_mask_stone(L, a)
        domes = blur1(1.0 - m, 5.0)
        return domes * 0.85 + fine_noise(L.shape, 1.6, 16) * 0.07
    if name == "clay":
        return 0.5 + fine_noise(L.shape, 20, 17) * 0.22 \
            + fine_noise(L.shape, 1.2, 18) * 0.08
    if name == "brick":
        m = mortar_mask_brick(L, a)
        return blur1(1.0 - m, 2.2) * 0.8 + fine_noise(L.shape, 1.4, 19) * 0.05
    if name == "tile":
        return blur1(L, 2.0) * 0.9 + fine_noise(L.shape, 1.0, 20) * 0.05
    if name == "iron":
        pits = fine_noise(L.shape, 0.7, 21)
        return 0.5 - np.clip(pits - 0.55, 0, 1) * 0.5 \
            + fine_noise(L.shape, 18, 22) * 0.12
    if name == "copper":
        return 0.5 + fine_noise(L.shape, 2.5, 23) * 0.03
    if name == "metalroof":
        return blur1(L, 1.4) * 0.75 + fine_noise(L.shape, 1.2, 24) * 0.05
    if name == "plaster":
        return 0.5 + fine_noise(L.shape, 22, 25) * 0.14 \
            + fine_noise(L.shape, 1.6, 26) * 0.05
    return np.full(L.shape, 0.5)


NORMAL_STRENGTH = {
    "planks": 1.6, "thatch": 1.05, "earth": 0.7, "bark": 2.0,
    "stone": 1.9, "clay": 0.7, "brick": 1.5, "tile": 1.7,
    "iron": 0.8, "copper": 0.4, "metalroof": 1.3, "plaster": 0.6,
}


def build_rough(name, a):
    """Absolute roughness in [0,1] (stored as 0..255)."""
    L = lum(a)
    if name == "planks":
        r = 0.80 + (blur1(L, 3) - 0.5) * 0.06
    elif name == "thatch":
        r = np.full(L.shape, 0.97)
    elif name == "earth":
        r = np.full(L.shape, 0.95)
    elif name == "bark":
        r = np.full(L.shape, 0.93)
    elif name == "stone":
        m = mortar_mask_stone(L, a)
        r = 0.86 + m * 0.11
    elif name == "clay":
        r = np.full(L.shape, 0.94)
    elif name == "brick":
        m = mortar_mask_brick(L, a)
        r = 0.84 + m * 0.13
    elif name == "tile":
        r = 0.80 + (blur1(L, 3) - 0.5) * 0.08
    elif name == "iron":
        r = 0.55 + (blur1(L, 6) - 0.42) * 0.35
    elif name == "copper":
        teal = ((a[..., 1] > a[..., 0] + 0.02) &
                (a[..., 2] > a[..., 0] - 0.02)).astype(np.float64)
        teal = blur1(teal, 2.0)
        r = 0.36 + teal * 0.38 + fine_noise(L.shape, 9, 31) * 0.05
    elif name == "metalroof":
        r = 0.52 + (blur1(L, 4) - 0.5) * 0.10
    elif name == "plaster":
        r = np.full(L.shape, 0.92)
    else:
        r = np.full(L.shape, 0.9)
    return (np.clip(r, 0.05, 1.0) * 255).astype(np.uint8)


# ------------------------------------------------------------ main

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    PREV.mkdir(parents=True, exist_ok=True)
    sheets = {n: Image.open(SRC / f"{n}.jpg").convert("RGB")
              for n in ("sheet-1", "sheet-2", "sheet-3")}
    report = {}
    for name, (sheet, quad, mode, tile_m) in MATERIALS.items():
        src = sheets[sheet]
        qw, qh = src.width // 2, src.height // 2
        qx, qy = QUAD[quad]
        crop = src.crop((qx * qw + INSET, qy * qh + INSET,
                         (qx + 1) * qw - INSET, (qy + 1) * qh - INSET))
        if mode.startswith("period"):
            crop = crop_periods(crop, mode)
        crop = crop.resize((SIZE, SIZE), Image.LANCZOS)
        a = grade(np.asarray(crop), name)
        if mode == "organic":
            a = crossfade(a)
        elif "+xf" in mode:
            # crossfade along x only (keep the period-cropped axis exact)
            s = a.shape[1]
            d = np.minimum(np.arange(s), s - 1 - np.arange(s)) + 0.5
            w = np.clip(1.0 - d / (s * 0.25), 0, 1).reshape(1, -1, 1)
            a = (1 - w) * a + w * np.roll(a, s // 2, axis=1)
        report[name] = {"tile_m": tile_m, "seam_ratio": round(seam_ratio(a), 3)}
        alb = (np.clip(a, 0, 1) * 255).astype(np.uint8)
        Image.fromarray(alb).save(OUT / f"{name}.png")
        nrm = height_to_normal(build_height(name, a),
                               NORMAL_STRENGTH[name])
        # data maps ship at 256px: plenty at game scale, keeps the
        # GLBs light (the albedo carries the detail)
        Image.fromarray(nrm).resize((256, 256), Image.BILINEAR).save(
            OUT / f"{name}_n.png")
        Image.fromarray(build_rough(name, a), "L").resize(
            (256, 256), Image.BILINEAR).save(OUT / f"{name}_r.png")
        tiled = Image.new("RGB", (SIZE * 2, SIZE * 2))
        for i in range(2):
            for j in range(2):
                tiled.paste(Image.fromarray(alb), (i * SIZE, j * SIZE))
        tiled.save(PREV / f"tiling-{name}.png")
        print(name, report[name])
    (HERE.parent / "texture-report.json").write_text(
        json.dumps(report, indent=1), encoding="utf-8")


# ------------------------------------------------------------ aux maps

def make_aux_textures():
    """Small sprites the sheets do not provide (all procedural)."""
    # log end grain: concentric rings + radial cracks + bark rim
    s = 256
    yy, xx = np.mgrid[0:s, 0:s]
    r = np.sqrt((xx - s / 2) ** 2 + (yy - s / 2) ** 2) / (s / 2)
    rings = 0.5 + 0.5 * np.sin(r * 42 + np.sin(np.arctan2(yy - s / 2, xx - s / 2) * 3) * 1.2)
    base = np.zeros((s, s, 3))
    base[:] = (0.72, 0.55, 0.34)
    base *= (0.82 + rings[..., None] * 0.30)
    ang = np.abs(np.sin(np.arctan2(yy - s / 2, xx - s / 2) * 5 + 0.7))
    base *= (1 - np.clip((ang - 0.965) * 14, 0, 1)[..., None] * 0.35)
    rim = np.clip((r - 0.86) * 9, 0, 1)
    base = base * (1 - rim[..., None]) + np.array([0.30, 0.19, 0.11]) * rim[..., None]
    Image.fromarray((np.clip(base, 0, 1) * 255).astype(np.uint8)).save(
        OUT / "log_end.png")

    def radial_alpha(size, inner, power=1.6):
        yy, xx = np.mgrid[0:size, 0:size]
        d = np.sqrt((xx - size / 2) ** 2 + (yy - size / 2) ** 2) / (size / 2)
        a = np.clip(1 - d, 0, 1) ** power
        a[d < inner] = 1.0
        return (a * 255).astype(np.uint8)

    # soot decal: soft black patch (alpha only; colour is black)
    s = 256
    img = Image.new("RGBA", (s, s), (8, 6, 5, 0))
    img.putalpha(Image.fromarray((radial_alpha(s, 0.15) * 0.97).astype(np.uint8)))
    img = img.filter(ImageFilter.GaussianBlur(3))
    img.save(OUT / "soot.png")

    # contact shadow: very soft dark radial gradient
    s = 256
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    img.putalpha(Image.fromarray((radial_alpha(s, 0.35, 1.4) * 0.34).astype(np.uint8)))
    img.save(OUT / "shadow.png")

    # flame card: teardrop silhouette, white-hot core to orange rim
    s = 256
    yy, xx = np.mgrid[0:s, 0:s]
    cx, cy = s / 2, s * 0.98
    wob = np.sin(yy / s * 9.0) * 6 * (yy / s)
    dx = (xx - cx - wob) / (s * 0.30)
    dy = (cy - yy) / (s * 0.92)
    body = dx ** 2 + np.clip(dy, 0, None) ** 2.4
    alpha = np.clip(1 - body, 0, 1)
    alpha = blur1(alpha, 2.0)
    core = np.clip(1 - (dx ** 2 * 2.6 + np.clip(dy - 0.06, 0, None) ** 2 * 3.2), 0, 1)
    col = np.zeros((s, s, 3))
    col[:] = (1.0, 0.30, 0.03)
    col = col * (1 - core[..., None]) + np.array([1.0, 0.78, 0.30]) * core[..., None]
    out = np.dstack([col, alpha])[..., [0, 1, 2, 3]]
    Image.fromarray((np.clip(out, 0, 1) * 255).astype(np.uint8)).save(
        OUT / "flame.png")
    print("aux textures written")


if __name__ == "__main__":
    main()
    make_aux_textures()
