#!/usr/bin/env python3
"""Bundle the processed gpt-env assets as WebP data URIs into
src/graphics/envTextures.ts (both graphics trees)."""
import base64, io, json, os
from PIL import Image

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJ = '/home/hatch/workspace/your_files/science-civilization-game'
ITEMS = {
    'streaks': ('waterfall-streaks.png', 1024, 84),
    'groundScree': ('ground-scree.png', 1024, 84),
    'shoreFoam': ('shore-foam.png', 1024, 86),
    'foamRing1': ('foam/foam-ring-1.png', 512, 86),
    'foamRing2': ('foam/foam-ring-2.png', 512, 86),
    'foamCluster1': ('foam/foam-cluster-1.png', 512, 86),
    'foamCluster2': ('foam/foam-cluster-2.png', 512, 86),
    'moss1': ('moss/moss-1.png', 512, 86),
    'moss2': ('moss/moss-2.png', 512, 86),
    'moss3': ('moss/moss-3.png', 512, 86),
}

uris = {}
total = 0
for key, (rel, maxw, q) in ITEMS.items():
    im = Image.open(os.path.join(BASE, rel))
    if im.width > maxw:
        im = im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'WEBP', quality=q, method=6)
    data = buf.getvalue()
    total += len(data)
    uris[key] = 'data:image/webp;base64,' + base64.b64encode(data).decode()
    print(key, im.size, len(data))

out = ('// Bundled gpt-env textures (WebP data URIs) — generated by\n'
       '// assets/gpt-env/tools/bundle_env.py from the processed GPT\n'
       '// sheets in assets/gpt-env/. Do not edit by hand.\n'
       'export const ENV_TEXTURES: Record<string, string> = {\n')
for k, v in uris.items():
    out += f'  {json.dumps(k)}: {json.dumps(v)},\n'
out += '};\n'
for tree in ('threejs-hd2d-graphics/src/graphics/envTextures.ts',
             'src/graphics/envTextures.ts'):
    with open(os.path.join(PROJ, tree), 'w') as f:
        f.write(out)
print('total bytes', total, '-> envTextures.ts written to both trees')
