#!/usr/bin/env python3
"""Bundle the processed branch sprites into branchTextures.ts
(data-URI WebP) for the graphics module, mirroring the gptTextures
pipeline. Writes both graphics trees (module originals + the game's
src/graphics copy) so they stay byte-identical.

WebP q88 keeps the alpha cutout crisp enough for alphaTest while
holding the whole set near ~0.3 MB.
"""
import base64
import io
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
REPO = os.path.normpath(os.path.join(ROOT, "..", ".."))
KEYS = {
    "branch_1": "branch-1.png",
    "branch_2": "branch-2.png",
    "branch_3": "branch-3.png",
    "branch_4": "branch-4.png",
    "branch_cluster": "branch-cluster.png",
}

lines = [
    "// GENERATED by assets/branch-cards/tools/bundle_textures.py — do not edit.",
    "// Branch/leaf card sprites (owner-provided sheet, processed in",
    "// assets/branch-cards/) for the card-built tree canopies.",
    "export const BRANCH_TEXTURES: Record<string, string> = {",
]
total = 0
for key, fn in KEYS.items():
    im = Image.open(os.path.join(ROOT, "sprites", fn)).convert("RGBA")
    buf = io.BytesIO()
    im.save(buf, "WEBP", quality=88, method=6)
    data = buf.getvalue()
    total += len(data)
    b64 = base64.b64encode(data).decode()
    lines.append(f"  {key}: 'data:image/webp;base64,{b64}',")
    print(key, fn, im.size, len(data), "bytes webp")
lines.append("};")
lines.append("")
src = "\n".join(lines)
for dest in (
    os.path.join(REPO, "threejs-hd2d-graphics", "src", "graphics", "branchTextures.ts"),
    os.path.join(REPO, "src", "graphics", "branchTextures.ts"),
):
    with open(dest, "w") as fh:
        fh.write(src)
    print("wrote", dest, len(src), "chars; webp total", total)
