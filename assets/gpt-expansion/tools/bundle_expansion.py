#!/usr/bin/env python3
"""Bundle the processed expansion assets into expansionTextures.ts
(WebP data URIs), mirroring the branch-cards bundling pattern:
EXPANSION_TEXTURES (sprays), GROUND_TEXTURES (terrain splat set),
LAVA_TEXTURES (albedo + emissive mask)."""
import base64, io, json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT.parents[1] / "threejs-hd2d-graphics" / "src" / "graphics" / "expansionTextures.ts"

def webp_uri(path, size, q=85):
    im = Image.open(path)
    if im.mode not in ("RGBA", "RGB"):
        im = im.convert("RGBA")
    im = im.resize((size, size), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "WEBP", quality=q, method=6)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode(), len(buf.getvalue())

def record(name, items):
    lines = [f"export const {name}: Record<string, string> = {{"]
    total = 0
    for key, (path, size) in items:
        uri, n = webp_uri(path, size)
        total += n
        lines.append(f"  {key}: '{uri}',")
    lines.append("};")
    return "\n".join(lines), total

sprays = [(k, (ROOT / "sprays" / f"{k}.png", 512)) for k in [
    "conifer-cedar", "conifer-pine", "conifer-young", "conifer-tip",
    "snow-conifer", "snow-broadleaf", "snow-shrub", "snow-icicle",
    "reed", "lily", "dry-shrub", "palm-frond"]]
sprays = [(k.replace("-", "_"), v) for k, v in sprays]
ground = [(k, (ROOT / "ground" / f"{f}.png", 512)) for k, f in [
    ("forest", "ground-forest"), ("mud", "ground-mud"),
    ("sand", "ground-sand-dry"), ("path", "ground-path-plain")]]
lava = [(k, (ROOT / "ground" / f, 512)) for k, f in [
    ("albedo", "lava-albedo.png"), ("emissive", "lava-emissive.png")]]

parts = ["// GENERATED by assets/gpt-expansion/tools/bundle_expansion.py — do not edit.",
         "// GPT world-expansion sheets (2026-11-07), processed in assets/gpt-expansion/."]
tot = 0
for name, items in (("EXPANSION_TEXTURES", sprays), ("GROUND_TEXTURES", ground), ("LAVA_TEXTURES", lava)):
    text, n = record(name, items)
    tot += n
    parts.append(text)
    print(name, "webp bytes:", n)
OUT.write_text("\n".join(parts) + "\n")
print("total webp bytes:", tot, "->", OUT)
