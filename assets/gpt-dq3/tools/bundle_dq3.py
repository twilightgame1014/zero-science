#!/usr/bin/env python3
"""Bundle the DQ3 textures the module needs as WebP data URIs
(dq3Textures.ts): broadleaf + scatter + waterside cards, smoke,
town ground tiles and the lava-flow pair."""
import base64, io, json
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent                     # assets/gpt-dq3
MOD = ROOT.parent.parent / "threejs-hd2d-graphics" / "src" / "graphics"

SPRAYS = ["broadleaf-bright", "broadleaf-droop", "broadleaf-deep", "broadleaf-light",
          "grass-tall", "grass-wide", "grass-pampas",
          "flower-white", "flower-yellow", "flower-pink",
          "leaf-pile", "pebbles", "floating-plants", "vine",
          "smoke-1", "smoke-2", "smoke-3"]
GROUND = ["town-cobble", "town-dirt-plain"]

def uri(img, max_size, quality=78):
    img = img.copy()
    img.thumbnail((max_size, max_size), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "WEBP", quality=quality, method=4)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()

out = {}
for name in SPRAYS:
    im = Image.open(ROOT / "sprays" / f"{name}.png").convert("RGBA")
    out[name] = uri(im, 512)
for name in GROUND:
    im = Image.open(ROOT / "ground" / f"{name}.png").convert("RGB")
    out[name] = uri(im, 512)
# lava pair: albedo keeps detail, emissive is mostly black (cheap)
alb = Image.open(ROOT / "ground" / "lava-flow.png").convert("RGB")
out["lava-flow"] = uri(alb, 512, 80)
emi = Image.open(ROOT / "ground" / "lava-flow-emissive.png").convert("RGB")
out["lava-flow-emissive"] = uri(emi, 512, 82)

total = sum(len(v) for v in out.values())
lines = ["// Bundled DQ3-density textures (WebP data URIs) — generated by",
         "// assets/gpt-dq3/tools/bundle_dq3.py from the processed GPT",
         "// sheets in assets/gpt-dq3/. Do not edit by hand.",
         "export const DQ3_TEXTURES: Record<string, string> = {"]
for k, v in out.items():
    lines.append(f"  {json.dumps(k)}: {json.dumps(v)},")
lines.append("};")
(MOD / "dq3Textures.ts").write_text("\n".join(lines) + "\n")
print(f"wrote dq3Textures.ts with {len(out)} textures, {total} chars")
